#!/usr/bin/env python3
"""Validate reviewed CA inputs and, optionally, the actual ESP-IDF output."""
import argparse
import hashlib
import json
import re
import struct
from pathlib import Path
from cryptography import x509
from cryptography.hazmat.primitives import serialization

FW = Path(__file__).resolve().parents[1] / "firmware-ESP32-LTE-M"


def require(ok, message):
    if not ok:
        raise SystemExit("TLS trust check failed: " + message)


def spki(cert):
    return cert.public_key().public_bytes(serialization.Encoding.DER,
                                          serialization.PublicFormat.SubjectPublicKeyInfo)


def main():
    parser = argparse.ArgumentParser(__doc__)
    parser.add_argument("--build-dir", type=Path)
    parser.add_argument("--write-header", action="store_true")
    args = parser.parse_args()
    manifest = json.loads((FW / "certs/manifest.json").read_text())
    pem = (FW / "certs/roots.pem").read_bytes()
    require(hashlib.sha256(pem).hexdigest() == manifest["bundle_sha256"], "CA file hash")
    certs = x509.load_pem_x509_certificates(pem)
    require(len(certs) == manifest["certificate_count"], "CA count")
    keys = manifest["distrusted_keys"]
    require(len(keys) == 8, "expected eight reviewed distrusted keys")
    denied = {bytes.fromhex(k["spki_der_hex"]) for k in keys}
    require(len(denied) == 8, "duplicate distrusted key")
    for key in keys:
        der = bytes.fromhex(key["spki_der_hex"])
        require(len(der) == 120, "SPKI length")
        serialization.load_der_public_key(der)
        require(hashlib.sha256(der).hexdigest() == key["sha256"], "SPKI hash")
    for cert in certs:
        names = cert.subject.get_attributes_for_oid(x509.NameOID.COMMON_NAME)
        require(not any(n.value in manifest["excluded_subjects"] for n in names), "excluded root")
        require(spki(cert) not in denied, "distrusted key in CA bundle")
    header = """/* Public SPKIs from rustls/webpki, see certs/manifest.json.
 * Generated by tools/check_tls_trust.py --write-header; never private keys. */
#ifndef WUPS_TLS_DISTRUST_H
#define WUPS_TLS_DISTRUST_H
#include <stdbool.h>
#include <stddef.h>
#include <string.h>
static const unsigned char WUPS_DISTRUSTED_SPKIS[8][120] = {
"""
    for key in keys:
        h = key["spki_der_hex"]
        header += "    /* " + key["name"] + " */\n    {" + ", ".join("0x" + h[i:i+2] for i in range(0, len(h), 2)) + "},\n"
    header += """};
static inline bool wups_tls_spki_distrusted(const unsigned char *spki, size_t len)
{
    if (spki == NULL || len != sizeof(WUPS_DISTRUSTED_SPKIS[0])) return false;
    for (size_t i = 0; i < sizeof(WUPS_DISTRUSTED_SPKIS) / sizeof(WUPS_DISTRUSTED_SPKIS[0]); ++i) {
        if (memcmp(spki, WUPS_DISTRUSTED_SPKIS[i], len) == 0) return true;
    }
    return false;
}
#endif
"""
    path = FW / "main/tls_distrust.h"
    if args.write_header:
        path.write_text(header)
    require(path.read_text() == header, "generated denylist header drift")
    for path in (FW / "main").glob("*.c"):
        if path.name != "tls_trust.c":
            require("esp_crt_bundle_attach" not in path.read_text(), "unguarded bundle attach: " + path.name)
    if args.build_dir:
        build = args.build_dir.resolve()
        config = json.loads((build / "config/sdkconfig.json").read_text())
        require(config.get("IDF_TARGET") == "esp32s3", "wrong hardware target")
        require(config.get("ESPTOOLPY_FLASHSIZE") == "4MB", "wrong flash size")
        require(config.get("BOOTLOADER_APP_ROLLBACK_ENABLE") is True, "OTA rollback disabled")
        require(config.get("MBEDTLS_HAVE_TIME") is True, "TLS clock disabled")
        require(config.get("MBEDTLS_HAVE_TIME_DATE") is True, "certificate validity dates unchecked")
        require(config.get("MBEDTLS_CERTIFICATE_BUNDLE_DEFAULT_NONE") is True, "SDK roots enabled")
        require(config.get("MBEDTLS_CUSTOM_CERTIFICATE_BUNDLE") is True, "custom roots disabled")
        require(config.get("MBEDTLS_CUSTOM_CERTIFICATE_BUNDLE_PATH") == "certs/roots.pem", "unexpected roots path")
        require(not config.get("MBEDTLS_CERTIFICATE_BUNDLE_DEPRECATED_LIST"), "deprecated roots enabled")
        candidates = list(build.rglob("x509_crt_bundle"))
        require(len(candidates) == 1, "expected one generated bundle")
        bundle = candidates[0].read_bytes()
        first = struct.unpack_from("<I", bundle)[0]
        require(first > 0 and first % 4 == 0 and first <= len(bundle), "invalid offset table")
        offsets = struct.unpack_from("<" + "I" * (first // 4), bundle)
        actual = []
        for i, off in enumerate(offsets):
            require(off >= first and off + 4 <= len(bundle), "invalid cert offset")
            n, k = struct.unpack_from("<HH", bundle, off)
            end = off + 4 + n + k
            require(end == (offsets[i+1] if i+1 < len(offsets) else len(bundle)), "invalid cert length")
            actual.append((bundle[off+4:off+4+n], bundle[off+4+n:end]))
        expected = sorted((c.subject.public_bytes(), spki(c)) for c in certs)
        require(actual == expected, "generated bundle differs from reviewed roots")
        image = (build / "firmware-ESP32-LTE-M.bin").read_bytes()
        require(bundle in image, "reviewed bundle absent from image")
        require(all(key in image for key in denied), "denylist absent from image")
    print(f"TLS trust PASS: {len(certs)} roots, {len(keys)} blocked SPKIs" + (", compiled image checked" if args.build_dir else ""))

if __name__ == "__main__":
    main()
